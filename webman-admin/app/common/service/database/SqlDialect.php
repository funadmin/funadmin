<?php

declare(strict_types=1);

namespace app\common\service\database;

use InvalidArgumentException;
use support\Db;

/** 仅编译结构化生成定义，不转换或执行任意 SQL。 */
final class SqlDialect
{
    public function __construct(public readonly string $driver)
    {
        if (!in_array($driver, ['mysql', 'pgsql', 'sqlite'], true)) throw new InvalidArgumentException('不支持的 SQL 驱动');
    }

    public static function forConnection(?string $name = null): self
    {
        return new self(Db::connection($name)->getDriverName());
    }

    public function identifier(string $name): string
    {
        if (!preg_match('/\A[a-z_][a-z0-9_]*\z/D', $name) || ($this->driver === 'pgsql' && strlen($name) > 63)) throw new InvalidArgumentException('数据库标识符不合法：' . $name);
        return $this->driver === 'mysql' ? '`' . $name . '`' : '"' . $name . '"';
    }

    public function indexName(string $name): string
    {
        $limit = $this->driver === 'pgsql' ? 63 : 64;
        return strlen($name) <= $limit ? $name : substr($name, 0, $limit - 13) . '_' . substr(hash('sha256', $name), 0, 12);
    }

    public function literal(mixed $value): string
    {
        if ($value === null) return 'NULL';
        if (is_bool($value)) return $this->driver === 'pgsql' ? ($value ? 'TRUE' : 'FALSE') : ($value ? '1' : '0');
        if (is_int($value) || is_float($value)) return (string) $value;
        $value = (string) $value;
        if (str_contains($value, "\0")) throw new InvalidArgumentException('SQL 值不能包含空字节');
        $escaped = str_replace("'", "''", $value);
        if ($this->driver === 'mysql') $escaped = str_replace('\\', '\\\\', $escaped);
        return "'" . $escaped . "'";
    }

    public function type(string $type): string
    {
        $type = strtolower(trim($type));
        if ($this->driver !== 'pgsql') return $type;
        $type = preg_replace('/\s+/', ' ', $type);
        $simple = [
            'tinyint' => 'smallint', 'tinyint unsigned' => 'smallint', 'smallint' => 'smallint', 'smallint unsigned' => 'integer',
            'mediumint' => 'integer', 'mediumint unsigned' => 'integer', 'int' => 'integer', 'integer' => 'integer',
            'int unsigned' => 'bigint', 'integer unsigned' => 'bigint', 'bigint' => 'bigint', 'bigint unsigned' => 'numeric(20,0)',
            'tinyint(1)' => 'boolean', 'bool' => 'boolean', 'boolean' => 'boolean',
            'text' => 'text', 'tinytext' => 'text', 'mediumtext' => 'text', 'longtext' => 'text',
            'json' => 'jsonb', 'jsonb' => 'jsonb', 'uuid' => 'uuid', 'date' => 'date', 'time' => 'time without time zone',
            'datetime' => 'timestamp without time zone', 'timestamp' => 'timestamp without time zone',
            'timestamp without time zone' => 'timestamp without time zone', 'timestamp with time zone' => 'timestamp with time zone',
            'time without time zone' => 'time without time zone', 'float' => 'real', 'double' => 'double precision',
            'double precision' => 'double precision', 'real' => 'real',
        ];
        if (isset($simple[$type])) return $simple[$type];
        if (preg_match('/\A(?:varchar|character varying|char|character)\(([1-9][0-9]{0,5})\)\z/D', $type, $match)) {
            return (str_starts_with($type, 'varchar') || str_starts_with($type, 'character varying') ? 'varchar' : 'char') . '(' . $match[1] . ')';
        }
        if (preg_match('/\A(?:decimal|numeric)\(([1-9][0-9]{0,2}),\s*([0-9]{1,3})\)\z/D', $type, $match) && (int) $match[2] <= (int) $match[1]) return 'numeric(' . $match[1] . ',' . $match[2] . ')';
        throw new InvalidArgumentException('PostgreSQL 不支持自动生成字段类型：' . $type);
    }

    public function column(array $field): string
    {
        $name = (string) $field['name'];
        $type = $this->type((string) $field['dbType']);
        $primary = (bool) ($field['primary'] ?? false);
        $identity = $primary && preg_match('/\A(?:smallint|integer|bigint)\z/D', $type);
        if ($primary && $type === 'numeric(20,0)') throw new InvalidArgumentException('PostgreSQL identity 主键不能使用 unsigned bigint，请使用 bigint');
        $sql = $this->identifier($name) . ' ' . $type;
        if ($identity && $this->driver === 'pgsql') $sql .= ' GENERATED BY DEFAULT AS IDENTITY';
        $sql .= ($field['nullable'] ?? false) ? ' NULL' : ' NOT NULL';
        if (!$identity && array_key_exists('default', $field) && $field['default'] !== null) {
            $default = $field['default'];
            if ($type === 'boolean') {
                $default = filter_var($default, FILTER_VALIDATE_BOOL, FILTER_NULL_ON_FAILURE);
                if ($default === null) throw new InvalidArgumentException('字段 ' . $name . ' boolean 默认值不合法');
            }
            $sql .= ' DEFAULT ' . $this->literal($default);
        }
        if ($primary && $this->driver === 'mysql' && str_contains($type, 'int')) $sql .= ' AUTO_INCREMENT';
        return $sql;
    }

    public function createTable(string $table, array $fields, string $comment = '', array $foreignKeys = []): string
    {
        $quoted = $this->identifier($table);
        $columns = $indexes = $comments = $primary = [];
        foreach ($fields as $field) {
            $name = (string) $field['name'];
            $columns[] = '  ' . $this->column($field);
            if ($field['primary'] ?? false) $primary[] = $this->identifier($name);
            if (($field['unique'] ?? false) || ($field['search'] ?? false) || ($field['relation'] ?? '') !== '') {
                $indexes[] = $this->createIndex($table, $name, (bool) ($field['unique'] ?? false));
            }
            if (($field['comment'] ?? '') !== '' && $this->driver === 'pgsql') $comments[] = 'COMMENT ON COLUMN ' . $quoted . '.' . $this->identifier($name) . ' IS ' . $this->literal($field['comment']) . ';';
        }
        if ($primary !== []) $columns[] = '  PRIMARY KEY (' . implode(', ', $primary) . ')';
        foreach ($foreignKeys as $key) {
            $action = strtoupper($key['onDelete'] ?? 'RESTRICT');
            if (!in_array($action, ['RESTRICT', 'CASCADE', 'SET NULL', 'NO ACTION'], true)) throw new InvalidArgumentException('外键删除策略不合法');
            $columns[] = '  FOREIGN KEY (' . $this->identifier($key['column']) . ') REFERENCES ' . $this->identifier($key['table']) . ' (' . $this->identifier($key['reference'] ?? 'id') . ') ON DELETE ' . $action;
        }
        $sql = "-- funadmin-physical-table\nCREATE TABLE IF NOT EXISTS " . $quoted . " (\n" . implode(",\n", $columns) . "\n)";
        $sql .= $this->driver === 'mysql' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT=' . $this->literal($comment) . ";\n" : ";\n";
        if ($comment !== '' && $this->driver === 'pgsql') $comments[] = 'COMMENT ON TABLE ' . $quoted . ' IS ' . $this->literal($comment) . ';';
        return $sql . implode("\n", array_merge($indexes, $comments)) . "\n";
    }

    public function createIndex(string $table, string $column, bool $unique = false): string
    {
        $name = $this->indexName(($unique ? 'uk_' : 'idx_') . $table . '_' . $column);
        return 'CREATE ' . ($unique ? 'UNIQUE ' : '') . 'INDEX ' . $this->identifier($name) . ' ON ' . $this->identifier($table) . ' (' . $this->identifier($column) . ');';
    }
}
