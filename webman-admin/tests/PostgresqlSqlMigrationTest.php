<?php

declare(strict_types=1);

namespace Tests;

use app\common\service\database\MigrationService;
use PHPUnit\Framework\TestCase;
use support\Db;

final class PostgresqlSqlMigrationTest extends TestCase
{
    public function test_native_sql_is_atomic_checked_and_uses_driver_directory(): void
    {
        if (getenv('TEST_PGSQL') !== '1') $this->markTestSkipped('需要隔离 PostgreSQL');
        $directory = sys_get_temp_dir() . '/pg-migration-' . bin2hex(random_bytes(5));
        mkdir($directory . '/pgsql', 0700, true);
        $schema = 'sql_' . bin2hex(random_bytes(4));
        $pdo = Db::connection()->getPdo();
        $pdo->exec('CREATE SCHEMA "' . $schema . '"');
        $pdo->exec('SET search_path TO "' . $schema . '"');
        $service = new MigrationService();
        file_put_contents($directory . '/001_fixture.sql', 'MYSQL ONLY;');
        file_put_contents($directory . '/pgsql/001_fixture.sql', 'CREATE TABLE fun_system_migration (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, scope varchar(100), version varchar(100), checksum varchar(64), executed_at bigint); CREATE TABLE fun_pg_fixture (id bigint PRIMARY KEY, title text); INSERT INTO fun_pg_fixture VALUES (1, $$中文;--保留$$);');
        try {
            self::assertSame(['001_fixture'], $service->runDirectory($directory));
            self::assertSame('中文;--保留', Db::table('pg_fixture')->value('title'));
            self::assertSame([], $service->runDirectory($directory));
            file_put_contents($directory . '/pgsql/002_fail.sql', "CREATE TABLE fun_failed (id integer); INSERT INTO fun_pg_fixture VALUES (1,'duplicate');");
            try {
                $service->runDirectory($directory);
                self::fail('必须回滚失败迁移');
            } catch (\Illuminate\Database\QueryException) {
                self::assertFalse(Db::schema()->hasTable('failed'));
                self::assertSame(1, Db::table('system_migration')->count());
            }
            file_put_contents($directory . '/pgsql/001_fixture.sql', 'SELECT 1;');
            $this->expectException(\RuntimeException::class);
            $this->expectExceptionMessage('checksum');
            $service->runDirectory($directory);
        } finally {
            $pdo->exec('SET search_path TO public');
            $pdo->exec('DROP SCHEMA "' . $schema . '" CASCADE');
            foreach (glob($directory . '/pgsql/*.sql') as $file) unlink($file);
            unlink($directory . '/001_fixture.sql');
            rmdir($directory . '/pgsql');
            rmdir($directory);
        }
    }
}
