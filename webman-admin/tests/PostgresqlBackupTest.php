<?php

declare(strict_types=1);

namespace Tests;

use app\admin\system\service\UpgradeDatabaseBackup;
use Illuminate\Database\Schema\Blueprint;
use PHPUnit\Framework\TestCase;
use support\Db;

final class PostgresqlBackupTest extends TestCase
{
    public function test_backup_rejects_external_schema_dependencies_and_insufficient_privileges(): void
    {
        if (getenv('TEST_PGSQL') !== '1') $this->markTestSkipped('需要隔离 PostgreSQL');
        $pdo = Db::connection()->getPdo();
        $schema = 'backup_dep_' . bin2hex(random_bytes(4));
        $role = 'backup_role_' . bin2hex(random_bytes(4));
        $pdo->exec('CREATE SCHEMA "' . $schema . '"');
        $pdo->exec('CREATE TABLE "' . $schema . '".parent(id integer PRIMARY KEY)');
        $pdo->exec('CREATE TABLE public."' . $schema . '_child"(parent_id integer REFERENCES "' . $schema . '".parent(id))');
        $pdo->exec('CREATE ROLE "' . $role . '" LOGIN PASSWORD \'isolated-backup-test\'');
        $config = Db::connection()->getConfig();
        $config['search_path'] = $schema;
        try {
            try {
                (new UpgradeDatabaseBackup(postgresqlConfig: $config))->preflight();
                self::fail('跨 schema 依赖必须拒绝');
            } catch (\RuntimeException $error) { self::assertStringContainsString('跨 schema', $error->getMessage()); }
            $config['username'] = $role;
            $config['password'] = 'isolated-backup-test';
            try {
                (new UpgradeDatabaseBackup(postgresqlConfig: $config))->preflight();
                self::fail('无临时建库权限必须拒绝');
            } catch (\RuntimeException $error) { self::assertStringContainsString('临时验证库权限', $error->getMessage()); }
        } finally {
            $pdo->exec('DROP TABLE public."' . $schema . '_child"');
            $pdo->exec('DROP SCHEMA "' . $schema . '" CASCADE');
            $pdo->exec('DROP ROLE "' . $role . '"');
        }
    }

    public function test_native_backup_restores_data_constraints_indexes_and_sequences(): void
    {
        if (getenv('TEST_PGSQL') !== '1') $this->markTestSkipped('需要隔离 PostgreSQL');
        $schema = 'backup_' . bin2hex(random_bytes(5));
        $pdo = Db::connection()->getPdo();
        $pdo->exec('CREATE SCHEMA "' . $schema . '"');
        $pdo->exec('CREATE TABLE "' . $schema . '".parent (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title text UNIQUE)');
        $pdo->exec('CREATE TABLE "' . $schema . '".child (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id bigint REFERENCES "' . $schema . '".parent(id), payload jsonb)');
        $pdo->exec('CREATE INDEX child_parent_idx ON "' . $schema . '".child(parent_id)');
        $pdo->exec('INSERT INTO "' . $schema . '".parent(title) VALUES (\'中文\')');
        $pdo->exec('INSERT INTO "' . $schema . '".child(parent_id,payload) VALUES (1,\'{"value":"中文"}\')');
        $root = sys_get_temp_dir() . '/pg-backup-' . bin2hex(random_bytes(5));
        mkdir($root, 0700);
        $path = $root . '/database.snapshot';
        $config = Db::connection()->getConfig();
        $config['search_path'] = $schema;
        $service = new UpgradeDatabaseBackup(postgresqlConfig: $config);
        try {
            $hash = $service->backup($path);
            self::assertSame(hash_file('sha256', $path), $hash);
            $pdo->exec('UPDATE "' . $schema . '".parent SET title=\'changed\'');
            $lock = $pdo->prepare('SELECT pg_advisory_lock(hashtext(?))');
            $lock->execute(['funadmin-restore:' . $config['database'] . ':' . $schema]);
            try {
                $service->restore($path, $hash);
                self::fail('并发恢复必须拒绝');
            } catch (\RuntimeException $error) { self::assertStringContainsString('恢复正在执行', $error->getMessage()); }
            finally {
                $unlock = $pdo->prepare('SELECT pg_advisory_unlock(hashtext(?))');
                $unlock->execute(['funadmin-restore:' . $config['database'] . ':' . $schema]);
            }
            $guard = 'pg_restore_guard_' . bin2hex(random_bytes(4));
            $pdo->exec('CREATE FUNCTION public.' . $guard . '() RETURNS event_trigger LANGUAGE plpgsql AS $$ BEGIN IF TG_TAG=\'DROP SCHEMA\' THEN RAISE EXCEPTION \'restore test rejection\'; END IF; END $$');
            $pdo->exec('CREATE EVENT TRIGGER ' . $guard . ' ON ddl_command_start EXECUTE FUNCTION public.' . $guard . '()');
            try {
                $service->restore($path, $hash);
                self::fail('恢复失败必须回滚');
            } catch (\RuntimeException $error) {
                self::assertStringContainsString('客户端执行失败', $error->getMessage());
                self::assertSame('changed', $pdo->query('SELECT title FROM "' . $schema . '".parent')->fetchColumn());
            } finally {
                $pdo->exec('DROP EVENT TRIGGER ' . $guard);
                $pdo->exec('DROP FUNCTION public.' . $guard . '()');
            }
            $pdo->exec('CREATE TABLE "' . $schema . '".extra_table (id integer)');
            $service->restore($path, $hash);
            self::assertSame('中文', $pdo->query('SELECT title FROM "' . $schema . '".parent')->fetchColumn());
            self::assertSame(1, (int) $pdo->query('SELECT COUNT(*) FROM "' . $schema . '".child')->fetchColumn());
            self::assertSame(2, (int) $pdo->query('INSERT INTO "' . $schema . '".parent(title) VALUES (\'新增\') RETURNING id')->fetchColumn());
            self::assertNull($pdo->query("SELECT to_regclass('" . $schema . ".extra_table')")->fetchColumn() ?: null);
            $pdo->beginTransaction();
            try {
                $pdo->exec('INSERT INTO "' . $schema . '".child(parent_id) VALUES (999)');
                self::fail('外键必须恢复');
            } catch (\PDOException $error) { self::assertSame('23503', $error->getCode()); }
            finally { $pdo->rollBack(); }
            try {
                $service->restore($path, str_repeat('0', 64));
                self::fail('损坏指纹必须拒绝');
            } catch (\RuntimeException $error) { self::assertStringContainsString('SHA-256', $error->getMessage()); }
        } finally {
            $pdo->exec('DROP SCHEMA "' . $schema . '" CASCADE');
            foreach (glob($root . '/*') as $file) if (is_file($file)) unlink($file);
            rmdir($root);
        }
    }
}
