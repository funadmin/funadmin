import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import epIconPack from '@iconify-json/ep/icons.json' with { type: 'json' };

const output = resolve('src/styles/ep-icons.css');
const icons = epIconPack.icons ?? {};
const sourceRoots = [resolve('src'), resolve('../plugins')];
const sourceExts = new Set(['.vue', '.ts', '.tsx']);

function encodeSvg(svg) {
  return svg
    .replace(/"/g, "'")
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/{/g, '%7B')
    .replace(/}/g, '%7D')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .replace(/\s+/g, ' ');
}

function iconToRule(name, icon) {
  const width = icon.width ?? epIconPack.width ?? 1024;
  const height = icon.height ?? epIconPack.height ?? 1024;
  const body = icon.body ?? '';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}">${body}</svg>`;
  const dataUri = `data:image/svg+xml,${encodeSvg(svg)}`;

  return `.i-ep-${name}{--ep-icon:url("${dataUri}");display:inline-block;width:1em;height:1em;color:currentColor;background-color:currentColor;mask:var(--ep-icon) no-repeat center/contain;-webkit-mask:var(--ep-icon) no-repeat center/contain;vertical-align:-0.125em;}`;
}

const header = [
  '/* Generated by scripts/generate-ep-icons.mjs. */',
  '/* Element Plus icon classes used by the admin UI. */',
  '@layer utilities {',
  '',
].join('\n');

async function collectFiles(dir) {
  const files = [];
  let entries = [];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return files;
  }

  for (const entry of entries) {
    const fullPath = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === 'dist') continue;
      files.push(...(await collectFiles(fullPath)));
    } else if (sourceExts.has(fullPath.slice(fullPath.lastIndexOf('.')))) {
      files.push(fullPath);
    }
  }
  return files;
}

async function collectUsedIconNames() {
  const names = new Set();
  const files = (await Promise.all(sourceRoots.map(collectFiles))).flat();
  const pattern = /\bi-ep-([a-z0-9-]+)\b/g;

  for (const file of files) {
    const content = await readFile(file, 'utf8');
    for (const match of content.matchAll(pattern)) {
      names.add(match[1]);
    }
  }

  return names;
}

const usedIconNames = await collectUsedIconNames();
const missingIconNames = [...usedIconNames].filter((name) => !icons[name]);
if (missingIconNames.length) {
  throw new Error(`Unknown Element Plus icon names: ${missingIconNames.join(', ')}`);
}

const rules = [...usedIconNames]
  .sort((a, b) => a.localeCompare(b))
  .map((name) => iconToRule(name, icons[name]))
  .join('\n');

await mkdir(dirname(output), { recursive: true });
await writeFile(output, `${header}${rules}\n}\n`, 'utf8');

console.log(`Generated ${usedIconNames.size} Element Plus icon rules at ${output}`);
